// blockingHookEvents lists the events whose decision can block or steer the run.
var blockingHookEvents = map[string]string{
	"PreToolUse":       "can block the call or rewrite its arguments",
	"UserPromptSubmit": "can block the prompt",
	"Stop":             "can refuse to end the turn",
	"SubagentStop":     "can refuse to end a sub-agent run",
}

// ReferenceMarkdown renders the complete configuration reference.
func ReferenceMarkdown(opts ReferenceOptions) string {
	var b strings.Builder
	version := opts.Version
	if version == "" {
		version = "dev"
	}
	fmt.Fprintf(&b, "%s\n\n", ReferenceMarker)
	b.WriteString("# pigo configuration reference\n\n")
	fmt.Fprintf(&b, "Generated from the running binary (pigo %s) on every launch; the installed skill\n", version)
	b.WriteString("always describes the binary that produced it. Everything below is derived from the\n")
	b.WriteString("code that implements the behaviour, not maintained by hand.\n\n")

	b.WriteString("## Where configuration lives\n\n")
	b.WriteString("Lowest to highest precedence:\n\n")
	b.WriteString("1. Built-in defaults.\n")
	b.WriteString("2. `$XDG_CONFIG_HOME/pigo/config.toml` (default `~/.config/pigo/config.toml`).\n")
	b.WriteString("3. `$PIGO_HOME/config.json` (global) and `./.pigo/config.json` (project, trust-gated):\n")
	b.WriteString("   `model`, `provider`, `thinkingLevel`, `credentials`, `hooks`.\n")
	b.WriteString("4. `$PIGO_HOME/pigorc` (always) and `./.pigorc` (only in a trusted directory):\n")
	b.WriteString("   `option` values outrank both config files; exported variables join the environment.\n")
	b.WriteString("5. CLI flags (always win).\n\n")
	b.WriteString("A pigorc is a Bash script sourced by one `bash` process with `set -eu`. Any step that\n")
	b.WriteString("fails aborts the load and prints a warning; a missing bash, a timeout (15s), an unknown\n")
	b.WriteString("option key or a malformed value only warns and never blocks the launch.\n\n")

	b.WriteString("## pigorc DSL\n\n")
	b.WriteString("```bash\n")
	b.WriteString("# set any config option (see the table below); a repeated scalar option wins, a list appends\n")
	b.WriteString("option model \"zai/glm-4.6\"\n")
	b.WriteString("option allowed-tools read\n")
	b.WriteString("option reset allowed-tools          # clear a list\n\n")
	b.WriteString("# command hook (same wire contract as config.json hooks)\n")
	b.WriteString("hook add PreToolUse --matcher '^bash$' --timeout 5 --command './.pigo/hooks/no-rm.sh'\n\n")
	b.WriteString("# shell-function hook: the function name is the event (case/_-insensitive)\n")
	b.WriteString("PreToolUse() { grep -q 'rm -rf /' && { echo blocked >&2; exit 2; }; return 0; }\n\n")
	b.WriteString("# third-party provider (the endpoint)\n")
	b.WriteString("provider add mycorp --type openai --base-url \"https://llm.mycorp.com/v1\" \\\n")
	b.WriteString("  --env-var MYCORP_API_KEY --model mycorp-large\n")
	b.WriteString("provider remove mycorp\n\n")
	b.WriteString("# models (declared separately from the provider; --supports-images marks a vision model)\n")
	b.WriteString("model add mycorp-large --provider mycorp\n")
	b.WriteString("model add mycorp-vl --provider mycorp --supports-images --display-name \"MyCorp Vision\"\n")
	b.WriteString("model remove mycorp-vl\n\n")
	b.WriteString("# custom sub-agent (agents are defined in the pigorc only)\n")
	b.WriteString("agent add researcher --description \"Read-only researcher\" --prompt-file ./researcher.md \\\n")
	b.WriteString("  --tools read,grep --model claude-haiku-4 --thinking off --timeout 300\n")
	b.WriteString("agent hook researcher PreToolUse --matcher '^bash$' --command './hooks/no-bash.sh'\n")
	b.WriteString("agent remove researcher\n\n")
	b.WriteString("# MCP server (stdio: command/args/env; Streamable HTTP: url/headers)\n")
	b.WriteString("mcp add github --url https://api.githubcopilot.com/mcp/ \\\n")
	b.WriteString("  --header Authorization \"Bearer $GH_PAT\"\n")
	b.WriteString("mcp add local --command npx --arg -y --arg @modelcontextprotocol/server-filesystem --arg /tmp\n")
	b.WriteString("mcp add legacy --url https://legacy.example/mcp --transport sse\n")
	b.WriteString("mcp add hosted --url https://api.example.com/mcp --oauth   # OAuth on 401\n")
	b.WriteString("mcp remove github\n\n")
	b.WriteString("# environment (provider keys, base URLs, PIGO_* knobs)\n")
	b.WriteString("export ANTHROPIC_API_KEY=\"$(pass show anthropic)\"\n")
	b.WriteString("```\n\n")

	b.WriteString("## Options (`option <key> <value>`)\n\n")
	b.WriteString("Underscores and dashes are interchangeable in keys. The config.toml column is the\n")
	b.WriteString("equivalent file key.\n\n")
	b.WriteString("| key | type | config.toml | meaning | example |\n")
	b.WriteString("|-----|------|-------------|---------|---------|\n")
	for _, spec := range optionSpecs {
		toml := spec.TOML
		if toml == "" {
			toml = "-"
		}
		example := spec.Example
		if spec.Kind != optString && spec.Kind != optList && spec.Kind != optPushCaps {
			example = spec.Example
		}
		fmt.Fprintf(&b, "| `%s` | %s | `%s` | %s | `%s` |\n",
			spec.Key, escapePipes(spec.Type), toml, escapePipes(spec.Summary), escapePipes(example))
	}
	b.WriteString("\n")

	b.WriteString("## Third-party providers (`provider add` / `[[providers]]`)\n\n")
	b.WriteString("A defined provider behaves like a built-in one: `--provider <name>`, model-id inference,\n")
	b.WriteString("a bare `--model <name>` (first listed model), `/model` and the preset picker all see it.\n")
	b.WriteString("A provider describes an endpoint; declare models separately to give one id its own\n")
	b.WriteString("capabilities. Image support is declared on the model, never on the provider: one gateway\n")
	b.WriteString("routinely serves both vision and text-only ids.\n\n")
	writeFieldTable(&b, "field", providerFieldDocs)
	b.WriteString("\n")

	b.WriteString("## Models (`model add` / `[[models]]`)\n\n")
	b.WriteString("Models are declared independently of the provider table, so one gateway can serve both\n")
	b.WriteString("vision and text-only models. `supports_images` is the only image-capability setting and\n")
	b.WriteString("decides whether `view_image` (and `read` on an image file) hands the picture to the model\n")
	b.WriteString("or reports it back as text. Omitting the key leaves pigo's default for the provider kind:\n")
	b.WriteString("`false` for a custom endpoint, `true` for a built-in one. Declare the vision ids of a\n")
	b.WriteString("custom gateway explicitly, since its default is text-only.\n\n")
	writeFieldTable(&b, "field", modelFieldDocs)
	b.WriteString("\n")

	b.WriteString("## Custom sub-agents (`agent add`)\n\n")
	b.WriteString("Each definition becomes a tool named after the agent. Sub-agents are complete agents:\n")
	b.WriteString("own context, own persisted session (parented to the calling conversation), auto-compaction,\n")
	b.WriteString("and they never get the `question` tool — the parent asks and then continues the child with\n")
	b.WriteString("`session_id`. Set `background: true` on a call to run it in the background; the report\n")
	b.WriteString("arrives as a follow-up message and `task_output` can list or wait for jobs.\n\n")
	writeFieldTable(&b, "field", agentFieldDocs)
	b.WriteString("\nPer-agent hooks use `agent hook <name> <event> [--matcher RE] [--timeout N] --command CMD`;\n")
	b.WriteString("they are independent of the main agent's hooks unless `inherit_hooks` is set.\n\n")

	b.WriteString("## MCP servers (`mcp add` / `[[mcp]]`)\n\n")
	b.WriteString("A Model Context Protocol server contributes its tools to the agent, named\n")
	b.WriteString("`mcp__<server>__<tool>`. stdio servers are spawned (`command`/`args`/`env`); HTTP\n")
	b.WriteString("servers are Streamable HTTP endpoints (`url`/`headers`, JSON or SSE replies). A\n")
	b.WriteString("server that fails to start or initialize is reported and skipped, and `--no-tools`\n")
	b.WriteString("disables MCP along with the other tools. Servers advertising resources or prompts\n")
	b.WriteString("also get mcp__<server>__list_resources / read_resource and list_prompts / get_prompt;\n")
	b.WriteString("a tools/list_changed notification refreshes the tool list on the next turn.\n\n")
	writeFieldTable(&b, "field", mcpFieldDocs)
	b.WriteString("\n")

	b.WriteString("## Hook events\n\n")
	b.WriteString("| event | can it block? |\n")
	b.WriteString("|-------|---------------|\n")
	for _, event := range hooks.AllEvents {
		effect := "observe / inject context"
		if v, ok := blockingHookEvents[event]; ok {
			effect = v
		}
		fmt.Fprintf(&b, "| `%s` | %s |\n", event, effect)
	}
	b.WriteString("\nHook input is one line of JSON on stdin (event_type, session_id, project_dir, and\n")
	b.WriteString("event-specific fields); exit 0 allows, exit 2 blocks (stderr is the reason), and a JSON\n")
	b.WriteString("stdout may carry `decision`, `reason`, `additionalContext` and `updatedInput`.\n\n")

	b.WriteString("## Environment variables\n\n")
	writeFieldTable(&b, "variable", envVarDocs)
	b.WriteString("\n")

	if len(opts.Flags) > 0 {
		b.WriteString("## CLI flags\n\n")
		b.WriteString("Flags override every file layer. The flags below are the ones this binary registers.\n\n")
		b.WriteString("| flag | default | meaning |\n")
		b.WriteString("|------|---------|---------|\n")
		for _, f := range opts.Flags {
			name := "--" + f.Name
			if f.Shorthand != "" {
				name += ", -" + f.Shorthand
			}
			def := f.Default
			if def == "" {
				def = "-"
			}
			fmt.Fprintf(&b, "| `%s` | `%s` | %s |\n", name, escapePipes(def), escapePipes(f.Usage))
		}
		b.WriteString("\n")
	}

	b.WriteString("## Notes\n\n")
	b.WriteString("- Credential precedence: `--api-key` > environment (`env_var`, then `<NAME>_API_KEY`) > the\n")
	b.WriteString("  definition's inline key/credential > the config file.\n")
	b.WriteString("- `pigorc` and hook commands are trusted code: they run with your privileges. The project\n")
	b.WriteString("  `.pigorc` and project-layer hooks load only in a trusted directory.\n")
	b.WriteString("- Secrets belong in the environment or `$PIGO_HOME/.credentials.yaml` (mode 0600), not in\n")
	b.WriteString("  config files.\n")
	return b.String()
}

// writeFieldTable renders a fieldDoc table.
func writeFieldTable(b *strings.Builder, header string, rows []fieldDoc) {
	fmt.Fprintf(b, "| %s | type | meaning |\n", header)
	b.WriteString("|------|------|---------|\n")
	for _, row := range rows {
		fmt.Fprintf(b, "| `%s` | %s | %s |\n", row.Name, escapePipes(row.Type), escapePipes(row.Summary))
	}
}

// escapePipes keeps a Markdown table cell intact.
func escapePipes(s string) string { return strings.ReplaceAll(s, "|", `\|`) }

// WriteReference writes the generated reference to path, creating the directory.
// The write is atomic (temp file + rename) so a reader never sees a partial
// document, and a failure is returned for the caller to log at its discretion.
func WriteReference(path string, opts ReferenceOptions) error {
	if path == "" {
		return fmt.Errorf("config: empty reference path")
	}
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return err
	}
	tmp, err := os.CreateTemp(filepath.Dir(path), ".reference-*.md")
	if err != nil {
		return err
	}
	tmpName := tmp.Name()
	defer os.Remove(tmpName)
	if _, err := tmp.WriteString(ReferenceMarkdown(opts)); err != nil {
		tmp.Close()
		return err
	}
	if err := tmp.Close(); err != nil {
		return err
	}
	if err := os.Chmod(tmpName, 0o644); err != nil {
		return err
	}
	return os.Rename(tmpName, path)
}

// SkillOwnsReference reports whether the skill directory at dir is pigo's own
// generated-reference skill: its SKILL.md carries ReferenceMarker. It is the guard
// that keeps a user's hand-written skill of the same name untouched.
func SkillOwnsReference(dir string) bool {
	data, err := os.ReadFile(filepath.Join(dir, "SKILL.md"))
	if err != nil {
		return false
	}
	return strings.Contains(string(data), ReferenceMarker)
}

// flagDocs / buildVersion are published by package main right after flag parsing
// and read by the skill loader, which writes the reference. They are held in
// atomics so tests (and a future concurrent call path) stay race-free.
var (
	flagDocs     atomic.Pointer[[]FlagDoc]
	buildVersion atomic.Pointer[string]
)

// SetFlagDocs records the CLI flag surface for the generated reference.
func SetFlagDocs(docs []FlagDoc) {
	copied := append([]FlagDoc(nil), docs...)
	flagDocs.Store(&copied)
}

// CurrentFlagDocs returns the recorded flag surface (nil when none was set).
func CurrentFlagDocs() []FlagDoc {
	if p := flagDocs.Load(); p != nil {
		return *p
	}
	return nil
}

// SetBuildVersion records the running binary's version for the reference header.
func SetBuildVersion(v string) {
	buildVersion.Store(&v)
}

// CurrentVersion returns the recorded build version, or "dev".
func CurrentVersion() string {
	if p := buildVersion.Load(); p != nil && *p != "" {
		return *p
	}
	return "dev"
}
