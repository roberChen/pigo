// This file generates the configuration reference that ships with the built-in
// `pigorc` skill.
//
// The reference is not written by hand: it is rendered from the code registries
// that implement the configuration (the option table in options.go, the hook event
// list, the provider/agent definition structs, the environment variables, and the
// CLI flag set the caller passes in), so a configurable item cannot be added
// without appearing in the documentation. `pigo` rewrites the file on every launch,
// so the installed skill always describes the running binary.
//
// Reference_test.go enforces coverage: every config.toml field, every provider and
// agent definition field, every hook event and every PIGO_* environment variable
// read by the code must appear here, and the cmd/pigo test does the same for every
// CLI flag.
package config

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"
	"sync/atomic"

	"github.com/smallnest/pigo/internal/hooks"
)

// ReferenceMarker prefixes the generated file and also marks the built-in skill
// directory as pigo-owned (the skill's SKILL.md carries it), so a user's own
// `pigorc` skill — a different thing, a hand-written guide with the same name — is
// never overwritten.
const ReferenceMarker = "<!-- generated by pigo: pigorc configuration reference; do not edit -->"

// ReferenceFileName is the generated file's name inside the skill directory.
const ReferenceFileName = "reference.md"

// SkillsReferencePath returns the generated reference path for a skills dir
// (e.g. ~/.agents/skills → ~/.agents/skills/pigorc/reference.md).
func SkillsReferencePath(skillsDir string) string {
	if skillsDir == "" {
		return ""
	}
	return filepath.Join(skillsDir, "pigorc", ReferenceFileName)
}

// FlagDoc is one CLI flag row, supplied by the caller (package main owns the flag
// set, so it cannot be imported here).
type FlagDoc struct {
	Name      string
	Shorthand string
	Default   string
	Usage     string
}

// ReferenceOptions carries the caller-provided parts of the reference.
type ReferenceOptions struct {
	// Version is the running pigo version ("dev" for local builds).
	Version string
	// Flags lists every CLI flag, in registration order.
	Flags []FlagDoc
}

// fieldDoc is one row of a struct-field table (provider/agent definitions, env
// vars). The coverage tests keep these in sync with the structs.
type fieldDoc struct {
	Name    string
	Type    string
	Summary string
}

